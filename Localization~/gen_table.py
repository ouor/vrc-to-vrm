"""Regenerates ../Editor/LocalizationTable.cs from strings.json (the single source of UI texts).

strings.json: [{ "key", "en", "ko", "ja", "zh", "contexts" }]. Placeholders such as {0} or {1:0.00} must match across languages.
Run:  python gen_table.py
"""
import collections, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = ("en", "ko", "ja", "zh")  # order must match the UiLanguage enum
rows = json.load(open(os.path.join(HERE, "strings.json"), encoding="utf-8"))

placeholders = lambda s: collections.Counter(re.findall(r"\{\d+[^{}]*\}", s))
problems = [f'{r["key"]}/{l}' for r in rows for l in LANGS[1:] if r.get(l) and placeholders(r[l]) != placeholders(r["en"])]
if problems:
    sys.exit("placeholder mismatch: " + ", ".join(problems))


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


out = ["// <auto-generated> Generated by Localization~/gen_table.py from strings.json. Edit the JSON, not this file. </auto-generated>",
       "using System.Collections.Generic;", "", "namespace VrcToVrm", "{",
       "    internal static class LocalizationTable", "    {",
       "        // key -> { English, Korean, Japanese, Simplified Chinese }",
       "        public static readonly Dictionary<string, string[]> Strings = new Dictionary<string, string[]>", "        {"]
for r in sorted(rows, key=lambda r: r["key"]):
    out.append(f'            {{ {lit(r["key"])}, new[] {{ {", ".join(lit(r.get(l, "")) for l in LANGS)} }} }},')
out += ["        };", "    }", "}", ""]
target = os.path.join(HERE, "..", "Editor", "LocalizationTable.cs")
open(target, "w", encoding="utf-8").write("\n".join(out))
print(f"{len(rows)} keys -> {os.path.normpath(target)}")
